/**
 * Argus Core - Spectrogram Viewer Component
 * ==========================================
 * Audio spectrogram visualization with frequency analysis display.
 * 
 * Implements: PRIME_FRONTEND_DOCUMENT.md - Section 2.2 - components/visualization/SpectrogramViewer.tsx
 * 
 * Role: Display mel-spectrogram visualization showing frequency content over time.
 * Helps experts understand where audio anomalies are detected.
 * 
 * Integration:
 * - Used by: AudioAnalysisPanel.tsx
 * - Backend: Uses spectrogram_url from AudioResult, GET /api/v1/analyze/{id}/detail
 *   - Presigned MinIO URL for spectrogram image
 *   - Generated by backend analyzers/audio.py using librosa
 * 
 * Features:
 * - Mel-spectrogram image display
 * - Frequency axis labels (Hz)
 * - Time axis labels (seconds)
 * - Zoom controls for detailed inspection
 * - Color scale legend for amplitude/intensity
 * - Anomaly region highlighting (future)
 * - Playhead position indicator (future)
 * 
 * Component Contract (P0):
 * - Props interface defined
 * - Loading state: Shows skeleton for image loading
 * - Empty state: Shows placeholder when no spectrogram available
 * - Error state: Shows error message with retry option
 * - Accessibility: Alt text, ARIA labels
 * - data-testid: spectrogram-viewer, spectrogram-image, spectrogram-controls
 */

